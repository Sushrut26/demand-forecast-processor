"""
Application configuration.

All configuration is environment-driven so the same code runs locally and on
Render. Sensible defaults keep local development friction-free while production
secrets are injected via environment variables.
"""

import os
from functools import lru_cache


def _get_bool(name: str, default: bool) -> bool:
    raw = os.environ.get(name)
    if raw is None:
        return default
    return raw.strip().lower() in ("1", "true", "yes", "on")


def _get_int(name: str, default: int) -> int:
    raw = os.environ.get(name)
    if raw is None or not raw.strip():
        return default
    try:
        return int(raw)
    except ValueError:
        return default


class Settings:
    """Runtime settings resolved from environment variables."""

    def __init__(self) -> None:
        # --- Core ---
        self.APP_NAME = os.environ.get("APP_NAME", "Godrej Forecast Platform")
        self.SECRET_KEY = os.environ.get("SECRET_KEY", "dev-insecure-secret-change-me")
        self.ENV = os.environ.get("ENV", "development")

        # --- Database ---
        # Default to a local SQLite file so the app runs with zero setup.
        # In production set DATABASE_URL to the Supabase / Postgres connection string.
        self.DATABASE_URL = os.environ.get("DATABASE_URL", "sqlite:///./data/app.db")

        # --- Admin bootstrap (seeded on first startup) ---
        self.ADMIN_EMAIL = os.environ.get("ADMIN_EMAIL", "admin@example.com")
        self.ADMIN_PASSWORD = os.environ.get("ADMIN_PASSWORD", "admin12345")

        # --- Licensing ---
        # Ed25519 private key (PEM, base64 of the PEM, or raw). Generated by
        # tools/make_signing_key.py. If unset, a throwaway key is generated at
        # startup (fine for local testing; NOT for production, as keys won't
        # survive restarts).
        self.LICENSE_SIGNING_KEY = os.environ.get("LICENSE_SIGNING_KEY", "")
        self.PRODUCT_CODE = os.environ.get("PRODUCT_CODE", "GODREJ_FORECAST_PROCESSOR")
        self.DEFAULT_LICENSE_DAYS = _get_int("DEFAULT_LICENSE_DAYS", 2)

        # --- Storage (Supabase) ---
        self.SUPABASE_URL = os.environ.get("SUPABASE_URL", "")
        self.SUPABASE_SERVICE_KEY = os.environ.get("SUPABASE_SERVICE_KEY", "")
        self.SUPABASE_BUCKET = os.environ.get("SUPABASE_BUCKET", "forecast-files")
        # Local fallback dir for stored files when Supabase is not configured.
        self.LOCAL_STORAGE_DIR = os.environ.get("LOCAL_STORAGE_DIR", "./data/storage")
        # Temp dir for job processing (ephemeral files always live here first).
        self.WORK_DIR = os.environ.get("WORK_DIR", "./data/work")

        # --- Compute guardrails (protect free-tier memory) ---
        self.MAX_UPLOAD_MB = _get_int("MAX_UPLOAD_MB", 15)
        self.MAX_ROWS = _get_int("MAX_ROWS", 5000)
        self.MAX_CATEGORY_COLUMNS = _get_int("MAX_CATEGORY_COLUMNS", 60)
        # Render free tier is single-CPU / 512MB; force sequential processing.
        self.FORECAST_WORKERS = _get_int("FORECAST_WORKERS", 1)

        # --- Retention safety sweep ---
        # Ephemeral (store_data=OFF) job files older than this are purged.
        self.EPHEMERAL_TTL_MINUTES = _get_int("EPHEMERAL_TTL_MINUTES", 60)

    @property
    def is_sqlite(self) -> bool:
        return self.DATABASE_URL.startswith("sqlite")

    @property
    def storage_configured(self) -> bool:
        return bool(self.SUPABASE_URL and self.SUPABASE_SERVICE_KEY)


@lru_cache
def get_settings() -> Settings:
    return Settings()


settings = get_settings()
